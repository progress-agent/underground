// Generates src/opening-vistas.js from the scout's vistas.json (s21:V2). Deterministic: no clock, no randomness.
// usage: node scripts/gen-opening-vistas.mjs <vistas.json> <out.js>
import fs from 'node:fs';
const [src, out] = process.argv.slice(2);
const list = JSON.parse(fs.readFileSync(src, 'utf8'));
const r2 = n => Math.round(n * 100) / 100;
const entries = list.filter(v => v.reachable === true).map(v => ({
  id: v.id, name: v.name, E: v.E, L: v.L, C: { x: v.C.x, z: v.C.z }, surfaceYAtC: v.surfaceYAtC, master: v.master }));
// today's landing (src/intro.js DEFAULTS end pose); C is 250 m behind E on the line from L through E.
const E = { x: -194.15, y: -39.00, z: -2162.75 }, L = { x: -988.47, y: 8.96, z: -1557.14 };
const hx = E.x - L.x, hz = E.z - L.z, hl = Math.hypot(hx, hz);
entries.push({ id: 'today', name: "Today's landing", E, L,
  C: { x: r2(E.x + hx / hl * 250), z: r2(E.z + hz / hl * 250) },
  surfaceYAtC: 130, /* approximate: not read from the terrain mesh (demo speed) */ master: 1.1 });
const body = `// opening-vistas.js: GENERATED by scripts/gen-opening-vistas.mjs from the scout's vistas.json (sprint 21Oct26w, lane V).
// Canonical scene units (x, z metres; y = metres x 5). Do not edit by hand.
export const OPENING_VISTAS = ${JSON.stringify(entries, null, 2)};
export const VISTA_BY_ID = Object.fromEntries(OPENING_VISTAS.map(v => [v.id, v]));
`;
fs.writeFileSync(out, body);
console.log('wrote', entries.length, 'vistas');
