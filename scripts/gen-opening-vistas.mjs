// Generates src/opening-vistas.js deterministically from the scout's vistas.json (sprint 21Oct26w, lane V).
// usage: node scripts/gen-opening-vistas.mjs <vistas.json> <out.js>
import fs from 'node:fs';
const [src, out] = process.argv.slice(2);
const all = JSON.parse(fs.readFileSync(src, 'utf8'));
const pick = ({ id, name, E, L, C, surfaceYAtC, master }) => ({ id, name, E, L, C, surfaceYAtC, master });
const list = all.filter(v => v.reachable === true).map(pick);
// 'today' is today's landing (src/intro.js DEFAULTS end pose); C is 250 m behind E on the line from L through E.
const E = { x: -194.15, y: -39.0, z: -2162.75 }, L = { x: -988.47, y: 8.96, z: -1557.14 };
const dx = E.x - L.x, dz = E.z - L.z, d = Math.hypot(dx, dz);
const C = { x: +(E.x + dx / d * 250).toFixed(2), z: +(E.z + dz / d * 250).toFixed(2) };
list.push({ id: 'today', name: "Today's landing near Oxford Circus", E, L, C, surfaceYAtC: null, master: 1.1 });
const text = `// opening-vistas.js: GENERATED by scripts/gen-opening-vistas.mjs from the scout's vistas.json (sprint 21Oct26w). Do not edit.
// 'today' has surfaceYAtC null: the director reads the terrain once at boot.
export const OPENING_VISTAS = ${JSON.stringify(list, null, 2)};
export const VISTA_BY_ID = Object.fromEntries(OPENING_VISTAS.map(v => [v.id, v]));
`;
fs.writeFileSync(out, text);
console.log('wrote', out, list.length, 'vistas');
